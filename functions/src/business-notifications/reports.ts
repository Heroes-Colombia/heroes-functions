/**
 * Manually send weekly report to a specific business
 */
export async function sendWeeklyReportToBusiness(
  businessId: string
): Promise<{ success: boolean; error?: string }> {
  const { getBusinessInfo } = await import("./emailSender");

  const business = await getBusinessInfo(businessId);
  if (!business) {
    return { success: false, error: "Business not found" };
  }

  const endDate = new Date();
  const startDate = new Date();
  startDate.setDate(startDate.getDate() - 7);

  const stats = await getBusinessStats(businessId, startDate, endDate);

  const emailContent = getWeeklyReportEmail(business, {
    stats: {
      views: stats.views,
      saves: stats.saves,
      clicks: stats.clicks,
    },
    top_promotions: stats.topPromotions,
  });

  const result = await sendBusinessNotification(
    business,
    "weekly_report",
    emailContent,
    {
      period: "weekly",
      stats: {
        views: stats.views,
        saves: stats.saves,
        clicks: stats.clicks,
      },
    }
  );

  return result;
}

